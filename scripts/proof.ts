// Writes measured proof into README.md (and SUBMISSION.md when it exists).
// Run with: npm run proof (node --experimental-strip-types scripts/proof.ts)
//
// Two proofs, each written between its own markers:
//   <!-- PROOF:BEGIN detector-bench --> ... <!-- PROOF:END detector-bench -->
//   <!-- PROOF:BEGIN unit-tests --> ... <!-- PROOF:END unit-tests -->
//
// Rules: rewrite only the text between markers, never touch files outside the repo,
// print one stdout line per proof, and always exit 0. A proof that cannot run writes
// "Not run in this build: <reason>." instead of a number.

import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { BENCH_TOLERANCE_DROPS, PROOF_STEP_RETRIES, PROOF_STEP_TIMEOUT_MS } from "../lib/config.ts";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const TARGETS = ["README.md", "SUBMISSION.md"];

const STATE_LABEL: Record<string, string> = {
  idle: "idle",
  warming: "too few drops",
  regular: "regular drip",
  irregular: "noisy room",
  quiet: "no regular drip",
};

function today(): string {
  return new Date().toISOString().slice(0, 10);
}

function reasonOf(err: unknown): string {
  const msg = err instanceof Error ? err.message : String(err);
  return msg.split("\n")[0].slice(0, 160);
}

async function detectorBench(): Promise<{ block: string; line: string }> {
  try {
    const { synthesizeClip } = await import("../lib/synth.ts");
    const { detectInBuffer } = await import("../lib/drip-detector.ts");
    const { benchClips } = await import("../lib/data/seed.ts");
    const { scoreRun } = await import("../lib/bench-score.ts");

    const lines = [
      `The six clips below are synthetic: generated by \`lib/synth.ts\` with a known drop count, not recorded at a real tap. A clip passes when the count is within ${BENCH_TOLERANCE_DROPS} drop of the truth and the verdict is right.`,
      "",
      "| Clip | Conditions | True drops | Counted | Verdict | ms |",
      "| --- | --- | ---: | ---: | --- | ---: |",
    ];
    let totalTrue = 0;
    let totalErr = 0;
    let passed = 0;
    for (const clip of benchClips) {
      const t0 = performance.now();
      const synth = synthesizeClip(clip);
      const { stats } = detectInBuffer(synth.samples, synth.sampleRate);
      const ms = Math.round(performance.now() - t0);
      const score = scoreRun(
        { hasDrops: clip.hasDrops, trueDrops: synth.trueDrops, counted: stats.count, state: stats.state },
        BENCH_TOLERANCE_DROPS
      );
      totalTrue += synth.trueDrops;
      totalErr += score.errorDrops;
      if (score.pass) passed++;
      const verdict = `${score.pass ? "pass" : "miss"}, ${STATE_LABEL[stats.state] ?? stats.state}`;
      lines.push(`| ${clip.title} | ${clip.conditions} | ${synth.trueDrops} | ${stats.count} | ${verdict} | ${ms} |`);
    }
    lines.push("");
    lines.push(
      `${passed} of ${benchClips.length} synthetic clips passed, with a total error of ${totalErr} drops across ${totalTrue} true drops, measured on Node ${process.version} on ${today()}.`
    );
    return {
      block: lines.join("\n"),
      line: `proof detector-bench: ${passed}/${benchClips.length} clips passed, ${totalErr} drops off across ${totalTrue}`,
    };
  } catch (err) {
    const reason = reasonOf(err);
    return { block: `Not run in this build: ${reason}.`, line: `proof detector-bench: not run (${reason})` };
  }
}

function unitTests(): { block: string; line: string } {
  try {
    const args = ["--experimental-strip-types", "--test", "tests/detector.test.ts"];
    let attempt = 0;
    let res = spawnSync(process.execPath, args, { cwd: ROOT, encoding: "utf8", timeout: PROOF_STEP_TIMEOUT_MS });
    // Retry only on timeout, and at most PROOF_STEP_RETRIES times.
    while (attempt < PROOF_STEP_RETRIES && (res.error as NodeJS.ErrnoException | undefined)?.code === "ETIMEDOUT") {
      attempt++;
      res = spawnSync(process.execPath, args, { cwd: ROOT, encoding: "utf8", timeout: PROOF_STEP_TIMEOUT_MS });
    }
    if (res.error) {
      const code = (res.error as NodeJS.ErrnoException).code;
      const reason =
        code === "ETIMEDOUT" ? `the test run took longer than ${PROOF_STEP_TIMEOUT_MS / 1000} seconds` : reasonOf(res.error);
      return { block: `Not run in this build: ${reason}.`, line: `proof unit-tests: not run (${reason})` };
    }
    const out = `${res.stdout ?? ""}\n${res.stderr ?? ""}`;
    // TAP reporter prints "# pass N"; the spec reporter prints "ℹ pass N".
    const pass = out.match(/^(?:#|ℹ)\s*pass\s+(\d+)/m);
    const fail = out.match(/^(?:#|ℹ)\s*fail\s+(\d+)/m);
    if (!pass || !fail) {
      const reason = `no test summary found (exit code ${res.status ?? "none"})`;
      return { block: `Not run in this build: ${reason}.`, line: `proof unit-tests: not run (${reason})` };
    }
    const p = Number(pass[1]);
    const f = Number(fail[1]);
    return {
      block: `${p} passed, ${f} failed. \`npm test\` ran \`tests/detector.test.ts\` on Node ${process.version} on ${today()}.`,
      line: `proof unit-tests: ${p} passed, ${f} failed`,
    };
  } catch (err) {
    const reason = reasonOf(err);
    return { block: `Not run in this build: ${reason}.`, line: `proof unit-tests: not run (${reason})` };
  }
}

function writeBlock(name: string, block: string): void {
  const begin = `<!-- PROOF:BEGIN ${name} -->`;
  const end = `<!-- PROOF:END ${name} -->`;
  for (const file of TARGETS) {
    const path = `${ROOT}${file}`;
    try {
      if (!existsSync(path)) continue;
      const text = readFileSync(path, "utf8");
      const a = text.indexOf(begin);
      const b = a === -1 ? -1 : text.indexOf(end, a + begin.length);
      if (a === -1 || b === -1) {
        console.log(`proof ${name}: markers missing in ${file}, skipped`);
        continue;
      }
      const next = `${text.slice(0, a + begin.length)}\n${block}\n${text.slice(b)}`;
      if (next !== text) writeFileSync(path, next, "utf8");
    } catch (err) {
      console.log(`proof ${name}: could not update ${file} (${reasonOf(err)})`);
    }
  }
}

async function main(): Promise<void> {
  const bench = await detectorBench();
  writeBlock("detector-bench", bench.block);
  console.log(bench.line);

  const tests = unitTests();
  writeBlock("unit-tests", tests.block);
  console.log(tests.line);
}

main()
  .catch((err) => {
    console.log(`proof: stopped early (${reasonOf(err)})`);
  })
  .finally(() => {
    process.exitCode = 0;
  });
